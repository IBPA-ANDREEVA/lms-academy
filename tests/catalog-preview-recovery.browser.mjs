import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.FRONTEND_URL||'http://localhost:3113';
const evidence=process.env.FRONTEND_EVIDENCE||'docs/qa/evidence/LAND03-04-2026-11-03';
await mkdir(evidence,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'chrome'});
const results=[];
try {
 const context=await browser.newContext({reducedMotion:'reduce'});
 const page=await context.newPage();page.setDefaultTimeout(10000);
 const diagnostics=[];page.on('console',m=>{if(m.type()==='error')diagnostics.push(m.text());});
 await page.goto(base+'/courses');await page.locator('#catalog-panel-courses article').first().waitFor();
 await page.evaluate(()=>{localStorage.setItem('lms.catalog.preview.v1','{"price":1}');localStorage.setItem('lms.catalog.preview-cart.v2','{"amount":1}');});
 await page.goto(base+'/cart');
 await page.getByRole('button',{name:'Попробовать снова',exact:true}).waitFor();
 await page.getByRole('button',{name:'Тестовое меню',exact:true}).click();
 await page.locator('#catalog-preview-panel [role="alert"]').waitFor();
 assert.ok(diagnostics.some(m=>m.includes('preview.catalog.restore.failed')));
 assert.ok(diagnostics.some(m=>m.includes('preview.cart.restore.failed')));
 await page.locator('#catalog-preview-panel').getByRole('button',{name:'Сбросить все демо-данные',exact:true}).click();
 await page.keyboard.press('Escape');await page.getByRole('heading',{name:'Пока здесь пусто'}).waitFor();
 await page.reload();await page.getByRole('heading',{name:'Пока здесь пусто'}).waitFor();
 results.push('Corrupt catalog/cart storage: visible recovery, structured diagnostics, reset/reload');
 const other=await context.newPage();await other.goto(base+'/courses');await other.locator('#catalog-panel-courses article').first().waitFor();
 await page.goto(base+'/courses');await page.locator('#catalog-panel-courses article').first().waitFor();
 await page.getByRole('button',{name:'Тестовое меню',exact:true}).click();
 await page.getByRole('button',{name:'Очистить каталог',exact:true}).click();
 await other.getByRole('heading',{name:'Курсы готовятся к публикации',exact:true}).waitFor();
 await page.getByRole('button',{name:'Сбросить все демо-данные',exact:true}).click();
 await other.locator('#catalog-panel-courses article').first().waitFor();
 results.push('Cross-tab catalog clear/reset');
 await context.close();
 const denied=await browser.newContext({reducedMotion:'reduce',viewport:{width:390,height:844}});
 await denied.addInitScript(()=>{Storage.prototype.setItem=function(){throw new DOMException('Denied','SecurityError');};});
 const blocked=await denied.newPage();blocked.setDefaultTimeout(10000);
 await blocked.goto(base+'/courses');await blocked.locator('#catalog-panel-courses article').first().waitFor();
 await blocked.getByRole('button',{name:'Тестовое меню',exact:true}).click();
 await blocked.getByRole('button',{name:'Добавить демо-курс',exact:true}).click();
 await blocked.locator('#catalog-preview-panel [role="alert"]').waitFor();
 assert.equal(await blocked.locator('#catalog-panel-courses article').count(),5);
 await blocked.getByRole('button',{name:'Курс в корзину',exact:true}).click();await blocked.keyboard.press('Escape');
 // Client navigation preserves memory-only changes when persistence is blocked.
 await blocked.getByRole('button',{name:/^Корзина, продуктов:/}).first().click();
 await blocked.getByRole('region',{name:'Предпросмотр корзины'}).getByText(/Не удалось сохранить тестовую корзину/).waitFor();
 await blocked.screenshot({path:evidence+'/preview-storage-denied-390.png',fullPage:true});
 results.push('Blocked storage: catalog updates in memory, visible catalog/cart write warnings');
 await denied.close();
 await writeFile(evidence+'/recovery-results.json',JSON.stringify({results},null,2));
 console.log('PASS preview recovery:',results);
} finally {await browser.close();}
