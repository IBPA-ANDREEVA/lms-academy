function page(
  id,
  name,
  group,
  route,
  phase,
  purpose,
  action,
  deps,
  issues,
  sections,
  source = R,
  anchor = "",
) {
  const sources = [
    source + (anchor ? "#" + anchor : ""),
    M,
    ...(route ? [S] : []),
  ];
  pages.push({
    schemaVersion: 1,
    id,
    name,
    group,
    route: route || null,
    routeStatus:
      id === "home" ? "implemented-starter" : route ? "proposed" : "unresolved",
    roles:
      group === "Student"
        ? ["student"]
        : group === "Trainer"
          ? ["trainer-curator"]
          : group === "Administration"
            ? ["administrator"]
            : group === "Manager"
              ? ["manager"]
              : ["guest", "student"],
    phase,
    purpose,
    primaryAction: action,
    requiredContent: sections.map((x) => x.content).join("\n"),
    dependencies: deps,
    issues: issues.split(" ").filter(Boolean),
    sources,
    implementation:
      id === "home"
        ? "Only the Next.js starter exists at /. Academy page not implemented."
        : "Not implemented. Screen composition is a proposal; a required capability does not mandate a separate route.",
    notes: "",
    revision: 1,
    status: "draft",
    approval: null,
    history: [],
    deletedSections: [],
    sections: sections.map((x, i) => ({
      id: `${id}--${x.key}`,
      name: x.name,
      position: i + 1,
      purpose: x.purpose,
      content: x.content,
      primaryAction: x.action,
      interactions: x.action
        ? `${x.action}. Поддержать клавиатуру; сохранить контекст при возврате и ошибке.`
        : "Чтение в логическом порядке; доступные переходы при наличии.",
      dependencies: deps,
      sources,
      phase: x.phase || phase,
      inclusion:
        x.phase === "Conditional" || x.phase === "Unresolved"
          ? "conditional"
          : "included",
      required: !x.phase || x.phase === phase,
      reviewed: false,
      desktop:
        "Ясная иерархия; связанные данные рядом; основной сценарий без декоративных отвлечений.",
      mobile:
        "Одна колонка в порядке чтения; перенос длинных названий; действия от 44px; без горизонтальной прокрутки.",
      states:
        "Загрузка: понятный статус. Нет данных: объяснение и следующий шаг. Ошибка: текст и повтор без потери контекста. Недоступное действие: причина. Успех: подтверждение фактического результата.",
      notes:
        x.notes ||
        "Структурное предложение, визуальная композиция не утверждена. Не добавлять новые продуктовые правила.",
    })),
  });
}
